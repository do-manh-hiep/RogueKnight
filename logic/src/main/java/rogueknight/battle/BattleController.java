package rogueknight.battle;

import rogueknight.action.ActionError;
import rogueknight.action.ActionKind;
import rogueknight.action.ActionRequest;
import rogueknight.action.ActionResult;
import rogueknight.action.BattleEvent;
import rogueknight.action.EnemyDecision;
import rogueknight.action.EnemyPolicy;
import rogueknight.action.ResultEvaluator;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import rogueknight.board.Position;

/**
 * Single entry point for Player Actions; owns turn/phase/result lifecycle around the resolver (C-04).
 * Flow per TD 5.11: validate -> resolve Player Action -> check terminal -> Turn+1 -> Enemy queue -> selection.
 */
public final class BattleController {
    private final BattleState state;
    private final EnemyTurnRunner enemyTurnRunner;

    BattleController(BattleState state) { this(state, EnemyPolicy.NONE); }

    BattleController(BattleState state, EnemyPolicy enemyPolicy) {
        BattleState suppliedState = Objects.requireNonNull(state, "state");
        // Copy through the immutable boundary so callers cannot retain a mutable alias.
        this.state = BattleState.fromSnapshot(suppliedState.snapshot());
        this.enemyTurnRunner = new EnemyTurnRunner(Objects.requireNonNull(enemyPolicy, "enemyPolicy"));
    }

    /** Creates a controller from an immutable setup/restore snapshot; mutable state never crosses the boundary. */
    public static BattleController fromSnapshot(BattleSnapshot snapshot, EnemyPolicy enemyPolicy) {
        return new BattleController(BattleState.fromSnapshot(Objects.requireNonNull(snapshot, "snapshot")), enemyPolicy);
    }

    public BattleSnapshot snapshot() { return state.snapshot(); }

    /** Backward-compatible Move-only highlight API. */
    public Set<Position> legalMoves(String actorId) {
        return legalTargets(actorId, ActionKind.MOVE);
    }

    /** Legal target squares are generated by the same rules used by submit(). */
    public Set<Position> legalTargets(String actorId, ActionKind kind) {
        if (!acceptsPlayerAction()) return Set.of();
        return KnightRules.legalTargets(state, actorId, kind);
    }

    /** WAIT is legal whenever the battle accepts actions and actorId is the live player Knight. */
    public boolean canWait(String actorId) {
        if (!acceptsPlayerAction()) return false;
        return KnightRules.validate(state, ActionRequest.waitAction(actorId)).isValid();
    }

    public ActionResult submit(ActionRequest request) {
        BattleSnapshot before = state.snapshot();
        if (state.result() != BattleResult.ONGOING) {
            return ActionResult.rejected(ActionError.BATTLE_FINISHED, before);
        }
        if (state.phase() != BattlePhase.PLAYER_SELECT) {
            return ActionResult.rejected(ActionError.WRONG_PHASE, before);
        }
        if (request == null || request.actorId() == null || request.kind() == null) {
            return ActionResult.rejected(ActionError.INVALID_PAYLOAD, before);
        }

        ValidationOutcome outcome = KnightRules.validate(state, request);
        if (!outcome.isValid()) return ActionResult.rejected(outcome.error(), before);

        List<BattleEvent> events = new ArrayList<>();
        state.setPhase(BattlePhase.PLAYER_RESOLVE);
        events.addAll(ActionResolver.resolve(state, outcome.plan()));
        // A Player Action that ends the battle does not advance the turn or run the Enemy queue (R-T03, R-R01).
        if (endIfTerminal(state, events)) return ActionResult.accepted(before, state.snapshot(), events);

        int oldTurn = state.globalTurn();
        state.advanceTurn();
        events.add(new BattleEvent.TurnAdvanced(oldTurn, state.globalTurn()));
        state.setPhase(BattlePhase.ENEMY_RESOLVE);
        events.addAll(enemyTurnRunner.run(state));
        // Safety net for phases (e.g. test stubs) that change the state without ending the battle themselves.
        endIfTerminal(state, events);
        if (state.result() == BattleResult.ONGOING) state.setPhase(BattlePhase.PLAYER_SELECT);
        return ActionResult.accepted(before, state.snapshot(), events);
    }

    /**
     * Commits a terminal result right after a resolved Action (C-06): FINISHED phase plus one BattleEnded event.
     * Returns true when the battle is over, including when it had already ended earlier in this submit.
     */
    static boolean endIfTerminal(BattleState state, List<BattleEvent> events) {
        if (state.result() != BattleResult.ONGOING) return true;
        BattleResult result = ResultEvaluator.evaluate(state);
        if (result == BattleResult.ONGOING) return false;
        state.finish(result);
        events.add(new BattleEvent.BattleEnded(result));
        return true;
    }

    private boolean acceptsPlayerAction() {
        return state.result() == BattleResult.ONGOING && state.phase() == BattlePhase.PLAYER_SELECT;
    }
}
